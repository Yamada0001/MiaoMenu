package com.fluxcraft.MiaoMenu.config;

import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

import java.nio.file.Path;

import org.bukkit.configuration.file.FileConfiguration;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import com.fluxcraft.MiaoMenu.MiaoMenu;

/**
 * 校验示例菜单的释放策略。
 *
 * <p>当前行为：只要 {@code settings.auto-generate-examples} 为 true，三种形态
 * （Java / 基岩 / Dialog）的示例与 commands.yml、tasks.yml 都会在缺失时释放。</p>
 */
class ConfigManagerExampleTest {
    @TempDir
    Path temporaryDirectory;

    @Test
    void autoGenerateReleasesEveryExampleForm() {
        MiaoMenu plugin = configuredPlugin(true);

        new ConfigManager(plugin).checkAndRefreshMenus();

        verify(plugin).saveResource("java_menus/test.yml", false);
        verify(plugin).saveResource("bedrock_menus/test.yml", false);
        verify(plugin).saveResource("dialog_menus/test.yml", false);
        verify(plugin).saveResource("commands.yml", false);
        verify(plugin).saveResource("tasks.yml", false);
    }

    @Test
    void autoGenerateDisabledReleasesNothing() {
        MiaoMenu plugin = configuredPlugin(false);

        new ConfigManager(plugin).checkAndRefreshMenus();

        verify(plugin, never()).saveResource("java_menus/test.yml", false);
        verify(plugin, never()).saveResource("bedrock_menus/test.yml", false);
        verify(plugin, never()).saveResource("dialog_menus/test.yml", false);
    }

    private MiaoMenu configuredPlugin(boolean autoGenerate) {
        MiaoMenu plugin = mock(MiaoMenu.class);
        FileConfiguration config = mock(FileConfiguration.class);
        when(plugin.getDataFolder()).thenReturn(temporaryDirectory.toFile());
        when(plugin.getConfig()).thenReturn(config);
        // 与 ConfigManager.MENU_VERSION 保持一致，走"仅补缺失示例"的分支
        when(config.getInt("menu-version", 0)).thenReturn(7);
        when(config.getBoolean("settings.auto-generate-examples", true)).thenReturn(autoGenerate);
        return plugin;
    }
}
